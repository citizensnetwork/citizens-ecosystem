/**
 * The control-plane line (`supabase-control/`): the engine owner's own small database.
 *
 * Two things are generated here, in the way the engine line's are:
 * - the catalogue check, from `supabase-control/control-objects.json` and the list of migration
 *   files: one SQL file that fails when a built control plane is not exactly what is listed;
 * - the seed of `control.grantable_features`, from the feature list in `@engine/config`: the
 *   features a tenant on the engine line can be allowed at all.
 */

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { FEATURE_KEYS, featureAvailableOn } from '@engine/config';
import { compareBlock, sqlTextArray } from './checks.ts';
import type { EngineMigration } from './migrations.ts';
import { CONTROL_DIR } from './paths.ts';
import { sqlLiteral } from './provision.ts';

export interface ControlObjects {
  /** Tables of the private schema `control`. */
  readonly tables: readonly string[];
  /** Functions of the private schema: helpers, trigger functions and the bootstrap. */
  readonly privateFunctions: readonly string[];
  /** Functions in `public`: the whole surface of the control plane. */
  readonly apiFunctions: readonly string[];
  /** Triggers, as `table.trigger`. */
  readonly triggers: readonly string[];
}

export const CONTROL_OBJECTS_PATH = resolve(CONTROL_DIR, 'control-objects.json');

export function loadControlObjects(path: string = CONTROL_OBJECTS_PATH): ControlObjects {
  return JSON.parse(readFileSync(path, 'utf8')) as ControlObjects;
}

/** The features of the engine line, in byte order. A citizens-line feature is never among them. */
export function grantableFeatures(): string[] {
  return FEATURE_KEYS.filter((key) => featureAvailableOn(key, 'engine')).sort();
}

/** The migration that seeds `control.grantable_features`. */
export function grantableFeaturesSql(version: string, name: string): string {
  const values = grantableFeatures()
    .map((feature) => `  (${sqlLiteral(feature)})`)
    .join(',\n');
  return [
    `-- Control plane ${version}: the features a tenant on the engine line can be allowed.`,
    '-- GENERATED by `ENGINE_DB_WRITE=1 pnpm --filter @engine/db test` from the feature list in',
    '-- packages/engine-config (every feature whose database line is the engine line). Do not edit',
    '-- by hand. A feature added later needs a NEW migration that inserts its row.',
    '',
    'insert into control.grantable_features (feature) values',
    `${values}`,
    'on conflict (feature) do nothing;',
    '',
    `insert into control.schema_migrations (version, name) values (${sqlLiteral(version)}, ${sqlLiteral(name)});`,
    '',
  ].join('\n');
}

const sorted = (values: readonly string[]) => [...new Set(values)].sort();

export function controlCatalogueCheckSql(
  objects: ControlObjects,
  migrations: readonly Pick<EngineMigration, 'version'>[],
): string {
  const publicFunctions = `select p.proname::text as name, p.oid, p.proacl
        from pg_catalog.pg_proc p
       where p.pronamespace = 'public'::regnamespace
         and not exists (select 1 from pg_catalog.pg_depend d where d.objid = p.oid and d.deptype = 'e')`;
  const privateFunctions = `select p.proname::text as name, p.oid, p.proacl
        from pg_catalog.pg_proc p where p.pronamespace = 'control'::regnamespace`;
  const callableBy = (role: string, functions: string) =>
    `select f.name from (${functions}) f where pg_catalog.has_function_privilege(${sqlLiteral(role)}, f.oid, 'execute')`;
  const openToAll = (functions: string) =>
    `select f.name from (${functions}) f where exists (select 1 from pg_catalog.aclexplode(f.proacl) g where g.grantee = 0)`;

  return `-- The catalogue check of the control-plane line.
-- GENERATED by \`pnpm --filter @engine/db test\` (with ENGINE_DB_WRITE=1) from control-objects.json
-- and the list of migration files. Do not edit by hand.
--
-- Run it against a database after the control-plane migrations. It changes nothing. It raises one
-- error that lists every problem: something missing, something nobody listed, or a function that
-- someone other than the signed-in role can call.

do $catalogue$
declare
  v_problems text[] := array[]::text[];
  v_tables constant text[] := ${sqlTextArray(sorted(objects.tables))};
  v_private_functions constant text[] := ${sqlTextArray(sorted(objects.privateFunctions))};
  v_api_functions constant text[] := ${sqlTextArray(sorted(objects.apiFunctions))};
  v_triggers constant text[] := ${sqlTextArray(sorted(objects.triggers))};
  v_versions constant text[] := ${sqlTextArray(migrations.map((migration) => migration.version))};
  v_nothing constant text[] := array[]::text[];
begin
  -- 1. Exactly the listed objects, no more and no fewer.${compareBlock(
    'table',
    'v_tables',
    `select c.relname::text as name from pg_catalog.pg_class c where c.relnamespace = 'control'::regnamespace and c.relkind in ('r', 'p')`,
  )}${compareBlock(
    'view or other relation in the private schema',
    'v_nothing',
    `select c.relname::text as name from pg_catalog.pg_class c where c.relnamespace = 'control'::regnamespace and c.relkind in ('v', 'm', 'f')`,
  )}${compareBlock(
    'relation in the public schema',
    'v_nothing',
    `select c.relname::text as name from pg_catalog.pg_class c
       where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm', 'f', 'S')
         and not exists (select 1 from pg_catalog.pg_depend d where d.objid = c.oid and d.deptype = 'e')`,
  )}${compareBlock('private function', 'v_private_functions', `select f.name from (${privateFunctions}) f`)}${compareBlock(
    'function',
    'v_api_functions',
    `select f.name from (${publicFunctions}) f`,
  )}${compareBlock(
    'trigger',
    'v_triggers',
    `select c.relname::text || '.' || t.tgname::text as name
        from pg_catalog.pg_trigger t
        join pg_catalog.pg_class c on c.oid = t.tgrelid
       where not t.tgisinternal and c.relnamespace in ('control'::regnamespace, 'public'::regnamespace)`,
  )}${compareBlock('migration', 'v_versions', `select m.version as name from control.schema_migrations m`)}

  -- 2. Who can call what. The signed-in role: exactly the listed functions. A visitor, the
  --    service role and "everyone": nothing at all, in either schema.${compareBlock(
    'function the signed-in role can call',
    'v_api_functions',
    callableBy('authenticated', publicFunctions),
  )}${compareBlock(
    'function a visitor can call',
    'v_nothing',
    callableBy('anon', publicFunctions),
  )}${compareBlock(
    'function the service role can call',
    'v_nothing',
    callableBy('service_role', publicFunctions),
  )}${compareBlock(
    'private function a data API role can call',
    'v_nothing',
    `select f.name || ' (' || r.role || ')' as name
        from (${privateFunctions}) f
        cross join unnest(array['anon', 'authenticated', 'service_role']) r(role)
       where pg_catalog.has_function_privilege(r.role, f.oid, 'execute')`,
  )}${compareBlock('function open to every role', 'v_nothing', openToAll(publicFunctions))}${compareBlock(
    'private function open to every role',
    'v_nothing',
    openToAll(privateFunctions),
  )}

  if pg_catalog.array_length(v_problems, 1) > 0 then
    raise exception 'CATALOGUE CHECK FAILED (% problems): %',
      pg_catalog.array_length(v_problems, 1), pg_catalog.array_to_string(v_problems, '; ');
  end if;
end;
$catalogue$;
`;
}
