/**
 * The wording that code outside the app reads by key.
 *
 * A database function or an edge function cannot import the message catalogue. So the engine's
 * neutral defaults for those messages are rows in `public.engine_wording` (source 'engine'),
 * seeded by a migration that this file writes; and a world's own words are rows with source
 * 'tenant', written when it publishes a configuration (see `buildPublishPayload`).
 */

import {
  createWorld,
  MESSAGE_KEYS,
  messageDefinition,
  parseTemplate,
  renderParts,
  resolveTerms,
  type Configuration,
  type Entitlements,
  type MessageKey,
} from '@engine/config';

/** The two kinds of code that read their text from the table. */
export const TABLE_RENDERERS = ['database', 'edge'] as const;
export type TableRenderer = (typeof TABLE_RENDERERS)[number];

export interface WordingRow {
  readonly key: MessageKey;
  readonly renderer: TableRenderer;
  readonly text: string;
}

/**
 * A world must name itself, so the engine has no default name. A default row is only read when a
 * world has not published its own words for that key; it then says "this app".
 */
export const STAND_IN_TERMS = { world: { one: 'this app' }, worldShort: { one: 'App' } } as const;

/** The engine's default text for every message a database or edge function writes out. */
export function engineWordingRows(): WordingRow[] {
  const terms = resolveTerms(STAND_IN_TERMS);
  const rows: WordingRow[] = [];
  for (const key of MESSAGE_KEYS) {
    const definition = messageDefinition(key);
    const renderer = TABLE_RENDERERS.find((candidate) => candidate === definition.renderedBy);
    if (renderer === undefined) continue;
    const { parts, problems } = parseTemplate(definition.default, definition.params ?? []);
    if (problems.length > 0) throw new Error(`The default of "${key}" is not a valid template.`);
    rows.push({ key, renderer, text: renderParts(parts, terms, {}, { keepParams: true }) });
  }
  return rows.sort((a, b) => a.key.localeCompare(b.key, 'en'));
}

const sqlLiteral = (text: string) => `'${text.replaceAll("'", "''")}'`;

/** The migration that seeds the engine's default rows. */
export function wordingSeedSql(version: string, name: string): string {
  const rows = engineWordingRows();
  const values = rows
    .map(
      (row) =>
        `  (${sqlLiteral(row.key)}, 'engine', ${sqlLiteral(row.renderer)}, ${sqlLiteral(row.text)})`,
    )
    .join(',\n');
  return [
    `-- Engine baseline ${version}: the engine's default wording, for code that reads its text by key.`,
    '-- GENERATED by `pnpm --filter @engine/db wording` from the message catalogue in',
    '-- packages/engine-config (every message a database function or an edge function writes out).',
    '-- Do not edit by hand. A value in curly brackets with a dollar sign is filled in when the text is used.',
    '',
    'insert into public.engine_wording (key, source, renderer, text) values',
    `${values}`,
    'on conflict (key, source) do update set renderer = excluded.renderer, text = excluded.text;',
    '',
    `insert into engine.schema_migrations (version, name) values (${sqlLiteral(version)}, ${sqlLiteral(name)});`,
    '',
  ].join('\n');
}

export interface PublishPayload {
  /** The configuration document, exactly as validated. */
  readonly document: Configuration;
  /** This world's words for the code that reads its text from the table. */
  readonly wording: Readonly<Record<TableRenderer, Readonly<Record<string, string>>>>;
}

/**
 * What a world's server hands to `publish_engine_configuration` after `validateConfiguration`
 * has accepted the document: the document itself, and the world's wording for the database and
 * the edge functions (terms filled in, `{$name}` values left in place).
 */
export function buildPublishPayload(
  configuration: Configuration,
  entitlements: Entitlements,
): PublishPayload {
  const world = createWorld(configuration, entitlements);
  return {
    document: configuration,
    wording: { database: world.wording('database'), edge: world.wording('edge') },
  };
}
